/** Writes the files into a directory, and says where each is */
export function writeTlsFiles(directory: string) {
  const files = {
    ca: join(directory, 'ca.crt'),
    certificate: join(directory, 'server.crt'),
    key: join(directory, 'server.key'),
    clientCertificate: join(directory, 'client.crt'),
    clientKey: join(directory, 'client.key'),
  };
  writeFileSync(files.ca, CA_CERTIFICATE);
  writeFileSync(files.certificate, SERVER_CERTIFICATE);
  writeFileSync(files.key, SERVER_KEY);
  writeFileSync(files.clientCertificate, CLIENT_CERTIFICATE);
  writeFileSync(files.clientKey, CLIENT_KEY);
  return files;
}
